// Packs the open Bloxd Map Editor asset library (Souls-equal/Bloxd_Map_Editor, schems/)
// into a single embeddable module so the studio (and the file:// standalone build) can
// offer all prefab builds offline.
//
// Usage: node tools/build-prefabs.mjs <schems-dir>
//   <schems-dir> must contain index.json plus the *.bloxdschem files, e.g. after:
//   gh api repos/Souls-equal/Bloxd_Map_Editor/tarball/main > /tmp/bme.tar.gz
//   mkdir -p /tmp/bme && tar xzf /tmp/bme.tar.gz -C /tmp/bme --strip-components=1
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { parseBloxdschem } from '../lib/bloxdschem.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dir=process.argv[2];
if(!dir||!fs.existsSync(path.join(dir||'','index.json'))){console.error('usage: node tools/build-prefabs.mjs <schems-dir containing index.json>');process.exit(1);}
const index=JSON.parse(fs.readFileSync(path.join(dir,'index.json'),'utf8'));
const parts=[],assets=[];let off=0,stale=0;
for(const a of index.assets){
  const bytes=fs.readFileSync(path.join(dir,a.f));
  // Recompute dimensions/block counts from the actual file bytes — the source index.json
  // is partially stale, so its metadata is only used for the asset type.
  const parsed=parseBloxdschem(bytes,a.f);
  const [x,y,z]=parsed.size;
  if(x!==a.x||y!==a.y||z!==a.z||parsed.total!==a.b)stale++;
  parts.push(bytes);
  assets.push({n:a.n,f:a.f,t:a.t,x,y,z,b:parsed.total,s:bytes.length,off});
  off+=bytes.length;
}
console.log('source index metadata was stale for',stale,'of',assets.length,'assets (recomputed from bytes)');
const payload=gzipSync(Buffer.concat(parts),{level:9}).toString('base64');
const out=path.join(root,'lib','prefab-data.js');
fs.writeFileSync(out,'// Generated by tools/build-prefabs.mjs — do not edit by hand.\n// Source: Souls-equal/Bloxd_Map_Editor schems/ (open asset pack, author-approved).\nexport default '+JSON.stringify({schema:1,count:assets.length,assets,payload})+';\n');
console.log('wrote lib/prefab-data.js:',assets.length,'assets,',off,'raw bytes ->',(payload.length/1048576).toFixed(2),'MB base64+gzip');
